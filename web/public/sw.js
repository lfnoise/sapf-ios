// sapf service worker.
//
// 1. Cross-origin isolation: the engine needs SharedArrayBuffer, which needs the page to be served with
//    Cross-Origin-Opener-Policy and Cross-Origin-Embedder-Policy headers. Static hosts such as GitHub Pages
//    can't set headers, so every same-origin response is re-served here with them added.
// 2. Offline use: responses are cached as they are fetched. Hashed build assets are served from the cache
//    first; everything else comes from the network when possible, so updates are picked up, and from the
//    cache when offline.

const CACHE = 'sapf-v1';

self.addEventListener('install', () => self.skipWaiting());

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

function withIsolationHeaders(response) {
  if (response.status === 0) return response; // opaque
  const headers = new Headers(response.headers);
  headers.set('Cross-Origin-Opener-Policy', 'same-origin');
  headers.set('Cross-Origin-Embedder-Policy', 'require-corp');
  headers.set('Cross-Origin-Resource-Policy', 'same-origin');
  return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
}

async function networkFirst(request) {
  const cache = await caches.open(CACHE);
  try {
    const response = await fetch(request);
    if (response.ok) cache.put(request, response.clone());
    return response;
  } catch (e) {
    const cached = await cache.match(request, { ignoreSearch: request.mode === 'navigate' });
    if (cached) return cached;
    throw e;
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) cache.put(request, response.clone());
  return response;
}

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (request.cache === 'only-if-cached' && request.mode !== 'same-origin') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  const hashed = url.pathname.includes('/assets/');
  event.respondWith((hashed ? cacheFirst(request) : networkFirst(request)).then(withIsolationHeaders));
});
